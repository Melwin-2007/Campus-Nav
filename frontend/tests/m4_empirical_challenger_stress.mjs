test('Dual-Unwrapping: Direct LocationOut payload (FastAPI backend contract)', async () => {
  const backendDirectLocation = {
    id: 3,
    name: 'Central Library',
    latitude: 17.65985,
    longitude: 75.90632,
    category_id: 2,
    facilities: ['Wi-Fi', 'Quiet Study'],
    is_active: true,
  };

  const mockResolve = async (id) => backendDirectLocation;
  const res = await simulateResolve('/qr/ait-loc-03', mockResolve);

  assert.strictEqual(res.status, 'SUCCESS');
  assert.strictEqual(res.location.id, 3);
  assert.strictEqual(res.location.name, 'Central Library');
  assert.strictEqual(res.flyTo.lat, 17.65985);
  assert.strictEqual(res.flyTo.lon, 75.90632);
  assert.strictEqual(res.error, null);
});

