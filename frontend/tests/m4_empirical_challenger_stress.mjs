test('Dual-Unwrapping: Lookup failure triggers fallback to getById for numeric codes', async () => {
  const mockResolveFail = async () => {
    throw new Error('404 Not Found');
  };
  const mockGetByIdSuccess = async (id) => ({
    id: id,
    name: 'Recovered Location ' + id,
    latitude: 17.6600,
    longitude: 75.9060,
  });

  // Numeric code '4' falls back to getById(4)
  const res = await simulateResolve('4', mockResolveFail, mockGetByIdSuccess);
  assert.strictEqual(res.status, 'SUCCESS_FALLBACK');
  assert.strictEqual(res.location.id, 4);
  assert.strictEqual(res.location.name, 'Recovered Location 4');

  // Non-numeric code 'LOC-ABCD' cannot fall back and returns descriptive error
  const resNonNumeric = await simulateResolve('LOC-ABCD', mockResolveFail, mockGetByIdSuccess);
  assert.strictEqual(resNonNumeric.status, 'LOOKUP_FAILED');
  assert.match(resNonNumeric.error, /Invalid or unrecognized campus QR code/i);
});

