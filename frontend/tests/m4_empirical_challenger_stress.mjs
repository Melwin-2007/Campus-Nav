// 1. Verbatim parseScannedText implementation under challenge
// ---------------------------------------------------------------------------
const parseScannedText = (text) => {
  const trimmed = text.trim();
  if (!trimmed) return '';

  try {
    if (trimmed.startsWith('/')) {
      const parts = trimmed.split('/').filter(Boolean);
      const qrIdx = parts.findIndex((p) => p === 'qr' || p === 'q');
      if (qrIdx !== -1 && qrIdx + 1 < parts.length) {
        return parts[qrIdx + 1].trim();
      }
    }

    if (trimmed.startsWith('http://') || trimmed.startsWith('https://')) {
      const url = new URL(trimmed);
      const locParam = url.searchParams.get('location_id') || url.searchParams.get('location');
      if (locParam) return locParam.trim();

      const pathParts = url.pathname.split('/').filter(Boolean);
      const qrIdx = pathParts.findIndex((p) => p === 'qr' || p === 'q');
      if (qrIdx !== -1 && qrIdx + 1 < pathParts.length) {
        return pathParts[qrIdx + 1].trim();
      }
    }
  } catch {}

  if (trimmed.startsWith('/q/') || trimmed.startsWith('/qr/')) {
    const parts = trimmed.split('/').filter(Boolean);
    if (parts.length >= 2) return parts[1].trim();
  }

  return trimmed;
};

// ---------------------------------------------------------------------------
// 2. Verbatim resolution unwrapping logic from QRScannerModal.tsx
// ---------------------------------------------------------------------------
function resolveLocationPayload(qrResult) {
  const resolvedLocation =
    qrResult?.location ??
    (qrResult && typeof qrResult.latitude === 'number' ? qrResult : null);
  return resolvedLocation;
}

// Full simulation of handleResolveCode
async function simulateResolve(rawCode, mockResolveApi, mockGetByIdApi) {
  const identifier = parseScannedText(rawCode);
  if (!identifier) {
    return { status: 'EMPTY_CODE', location: null, error: null };
  }

  try {
    const qrResult = await mockResolveApi(identifier);
    const resolvedLocation = resolveLocationPayload(qrResult);

    if (resolvedLocation) {
      return {
        status: 'SUCCESS',
        location: resolvedLocation,
        flyTo: { lat: resolvedLocation.latitude, lon: resolvedLocation.longitude, zoom: 18 },
        error: null,
      };
    } else {
      return {
        status: 'NO_LOCATION_DATA',
        location: null,
        error: 'QR code recognized but no associated location data was found.',
      };
    }
  } catch (err) {
    const numId = parseInt(identifier, 10);
    if (!isNaN(numId) && numId > 0 && mockGetByIdApi) {
      try {
        const loc = await mockGetByIdApi(numId);
        return {
          status: 'SUCCESS_FALLBACK',
          location: loc,
          flyTo: { lat: loc.latitude, lon: loc.longitude, zoom: 18 },
          error: null,
        };
      } catch {}
    }
    return {
      status: 'LOOKUP_FAILED',
      location: null,
      error: 'Invalid or unrecognized campus QR code. Please ensure code is valid or type location name into search.',
    };
  }
}

