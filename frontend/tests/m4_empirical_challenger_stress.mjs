test('QR Scanned Parsing: Relative deep links in various forms', () => {
  // Common paths generated by backend or printed on posters
  assert.strictEqual(parseScannedText('/qr/LOC-0001'), 'LOC-0001');
  assert.strictEqual(parseScannedText('/q/LOC-0001'), 'LOC-0001');
  assert.strictEqual(parseScannedText('/api/qr/LOC-0001'), 'LOC-0001');
  assert.strictEqual(parseScannedText('/api/v1/qr/LOC-0001'), 'LOC-0001');
  assert.strictEqual(parseScannedText('/v2/q/c499d613-25d0-4928-8922'), 'c499d613-25d0-4928-8922');
  assert.strictEqual(parseScannedText('/nested/path/to/qr/TOKEN123'), 'TOKEN123');
});

test('QR Scanned Parsing: Trailing slashes and duplicate slashes', () => {
  assert.strictEqual(parseScannedText('/qr/LOC-0001/'), 'LOC-0001');
  assert.strictEqual(parseScannedText('///qr///LOC-0001///'), 'LOC-0001');
  assert.strictEqual(parseScannedText('https://campus.edu//qr//LOC-0001/'), 'LOC-0001');
});

test('QR Scanned Parsing: Full absolute URLs with path or query params', () => {
  assert.strictEqual(parseScannedText('https://campusnav.edu/qr/LOC-100'), 'LOC-100');
  assert.strictEqual(parseScannedText('http://192.168.1.50:5173/q/ROOM-204'), 'ROOM-204');
  assert.strictEqual(parseScannedText('https://campusnav.edu/?location_id=14'), '14');
  assert.strictEqual(parseScannedText('https://campusnav.edu/map?location=8'), '8');
  assert.strictEqual(parseScannedText('https://campusnav.edu/?other=1&location_id=99&test=true'), '99');
});

test('QR Scanned Parsing: Boundary inputs and fallback handling', () => {
  assert.strictEqual(parseScannedText(''), '');
  assert.strictEqual(parseScannedText('   '), '');
  assert.strictEqual(parseScannedText('LOC-0001'), 'LOC-0001');
  assert.strictEqual(parseScannedText('14'), '14');
  assert.strictEqual(parseScannedText('/'), '/');
  assert.strictEqual(parseScannedText('/qr'), '/qr');
  assert.strictEqual(parseScannedText('/qr/'), '/qr/');
});

