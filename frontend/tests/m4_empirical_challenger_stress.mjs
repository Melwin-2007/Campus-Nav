test('Icon Mapping Logic: Medical vs AC/Parking collisions', () => {
  // Direct logic check replicating iconMapping.ts
  const getFacilityIconName = (facilityName) => {
    if (typeof facilityName !== 'string' || facilityName.trim() === '') {
      return 'CheckCircle2';
    }
    const lower = facilityName.toLowerCase().trim();

    // Medical first
    if (
      lower.includes('doctor') ||
      lower.includes('health') ||
      lower.includes('medical') ||
      lower.includes('first aid') ||
      lower.includes('emergency') ||
      lower.includes('pharmacy') ||
      lower.includes('clinic') ||
      lower.includes('infirmary') ||
      lower.includes('ambulance')
    ) {
      return 'HeartPulse';
    }

    // Climate / AC with word boundary
    if (lower.includes('air conditioning') || /\bac\b/i.test(lower) || lower.includes('hvac')) {
      return 'Wind';
    }

    // Parking with word boundary
    if (
      lower.includes('parking') ||
      /\b(car|cars|bay|bays|two-wheeler|two wheeler|garage|valet)\b/i.test(lower)
    ) {
      return 'Car';
    }

    return 'CheckCircle2';
  };

  assert.strictEqual(getFacilityIconName('Pharmacy'), 'HeartPulse', 'Pharmacy must not match ac');
  assert.strictEqual(getFacilityIconName('Emergency Care'), 'HeartPulse', 'Emergency Care must not match car');
  assert.strictEqual(getFacilityIconName('First Aid Kit'), 'HeartPulse');
  assert.strictEqual(getFacilityIconName('Doctor on Duty'), 'HeartPulse');

  assert.strictEqual(getFacilityIconName('AC Labs'), 'Wind', 'AC Labs matches \\bac\\b');
  assert.strictEqual(getFacilityIconName('Air Conditioning'), 'Wind');
  assert.strictEqual(getFacilityIconName('Central AC'), 'Wind');

  assert.strictEqual(getFacilityIconName('Car bays'), 'Car', 'Car bays matches parking');
  assert.strictEqual(getFacilityIconName('Two-wheeler bays'), 'Car');
  assert.strictEqual(getFacilityIconName('Visitor Parking'), 'Car');

  assert.strictEqual(getFacilityIconName(null), 'CheckCircle2');
  assert.strictEqual(getFacilityIconName(undefined), 'CheckCircle2');
  assert.strictEqual(getFacilityIconName(12345), 'CheckCircle2');
});
